#!/usr/bin/env python3
"""Write src/unit.cpp: the single compile unit that #includes every game source file in retail order.

RULES.md "Unity build": retail compiled the game C++ files as one unit, so `static` functions in one
file are called from others (with register arguments). Order comes from link/order.txt (retail address
order). Every file listed there gets a placeholder if it doesn't exist yet, so the layout is complete
from day one. Owner tool; agents edit the included files, never unit.cpp.
"""
import pathlib

BASE = pathlib.Path(__file__).resolve().parent.parent


def main():
    files = []
    for line in (BASE / "link" / "order.txt").read_text().splitlines():
        if line and not line.startswith("#"):
            tu = line.split("\t")[0]
            files.append(tu if tu.startswith("src/") else "src/" + tu)
    for f in files:
        p = BASE / f
        if not p.exists():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text("// %s: placeholder, no function reconstructed yet. Code goes here in retail order.\n" % p.name)
    out = ["// Generated by tools/gen_unit.py. Retail compiled all of these as one unit (RULES.md).",
           "// Do not edit by hand; edit the included files."]
    out += ['#include "%s"' % pathlib.Path(f).relative_to("src").as_posix() for f in files]
    (BASE / "src" / "unit.cpp").write_text("\n".join(out) + "\n")
    print("unit.cpp includes %d files" % len(files))


if __name__ == "__main__":
    main()
