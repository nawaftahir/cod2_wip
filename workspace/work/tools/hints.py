#!/usr/bin/env python3
"""hints.py <build dir> <BLOCKERS.md> <out.md> [skip names...]: same-size blocker diffs as worker hints.

Absolute addresses are normalized; listed rows differ only in the shown instructions.
"""
import re, sys
from pathlib import Path
import capstone, pefile

build, blockers, out, skip = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), set(sys.argv[4:])
anchor = '/home/nawaf/cod2/test/dev/cod2_wip/binaries/windows/1.0/gfx_d3d_mp_x86_s.dll'
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
ours = pefile.PE(str(build / 'gfx.dll'), fast_load=True).get_memory_mapped_image()
ret = pefile.PE(anchor, fast_load=True).get_memory_mapped_image()
mapf = (build / 'gfx.map').read_text()
norm = lambda i: i.mnemonic + ' ' + re.sub(r'0x[0-9a-f]{5,}', 'A', i.op_str)

rows, n = [], 0
for line in blockers.read_text().splitlines():
    c = [x.strip(' `') for x in line.split('|')]
    if len(c) < 7 or 'same size' not in c[5] or c[2] in skip:
        continue
    name, ra, size = c[2], int(c[3], 16), int(c[4].split('/')[1])
    m = re.search(r' \?' + re.escape(name) + r'@\S*\s+([0-9a-f]{8}) ', mapf)
    if not m:
        continue
    oa = int(m.group(1), 16)
    O = list(md.disasm(ours[oa - 0x10000000:oa - 0x10000000 + size], oa))
    R = list(md.disasm(ret[ra - 0x10000000:ra - 0x10000000 + size], ra))
    diff = [(a.address - oa, norm(a), norm(b)) for a, b in zip(O, R) if norm(a) != norm(b)]
    n += 1
    rows.append(f'## g{n}: {name}\nretail 0x{ra:x}, {size} bytes (ours same size), unblocks {c[6]} bytes. '
                f'{len(diff)} differing instructions; first ones:\n```\n' +
                '\n'.join(f'+{k:x}  ours: {a:<40} retail: {b}' for k, a, b in diff[:14]) + '\n```\n')
out.write_text('# Renderer queue for Gemini workers (generated by work/tools/hints.py)\n\n'
               'Rules: docs/WORKER_BRIEF.md. One row per worker; worktree .worktrees/gfx-gN, branch gfx/gN.\n'
               'Change only the source that explains the shown diff. Max 3 probes, then log to TRIED.\n\n'
               + '\n'.join(rows))
print(n, 'rows')
