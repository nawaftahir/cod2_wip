#!/usr/bin/env python3
"""blockers.py <build dir> <out.md>: rank unverified callees by game bytes they block.

A blocked caller already matches bytewise, so the i-th call in our copy and in
retail name the same callee; that pins each blocker's retail address.
"""
import collections, json, re, sys
from pathlib import Path
import capstone, pefile

work = Path(__file__).resolve().parents[1]
build, out = Path(sys.argv[1]), Path(sys.argv[2])
anchor = Path('/home/nawaf/cod2/test/dev/cod2_wip/binaries/windows/1.0/gfx_d3d_mp_x86_s.dll')
GAME = ((0x10001000, 0x10041db0), (0x10057990, 0x10062200))
game = lambda a: any(lo <= a < hi for lo, hi in GAME)
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)

def image(p):
    pe = pefile.PE(str(p), fast_load=True)
    return pe.get_memory_mapped_image(), pe.OPTIONAL_HEADER.ImageBase

def calls(img, base, a, n):
    return [int(i.op_str, 16) for i in md.disasm(img[a - base:a - base + n], a)
            if i.mnemonic == 'call' and i.op_str.startswith('0x')]

ours, obase = image(build / 'gfx.dll')
ret, rbase = image(anchor)
sym = {}
for m in re.finditer(r'^ 0001:\S+\s+(\S+)\s+([0-9a-f]{8}) ', (build / 'gfx.map').read_text(), re.M):
    sym.setdefault(m.group(1), int(m.group(2), 16))
name_at = {a: s for s, a in sym.items()}
size = {x['name']: x['size'] for x in json.load(open(build / 'cmp.json'))}
inv = {int(f['addr'], 16): f['size'] for f in json.load(open(work / 'proof/retail/functions_gfx10.json'))['functions']}
bind = json.load(open(build / 'bind.json'))

blocked = collections.Counter()
callers = collections.defaultdict(list)
raddr = {}
for s, v in bind.items():
    t = int(v['t'], 16)
    if not game(t) or not v.get('why') or s not in sym:
        continue
    pairs = zip(calls(ours, obase, sym[s], v['n']), calls(ret, rbase, t, v['n']))
    for w in v['why']:
        if not w.startswith('call '):
            continue
        callee = w[5:]
        blocked[callee] += v['n']
        callers[callee].append('%s/%d' % (s.split('@')[0].lstrip('?'), v['n']))
        for o, r in pairs:
            if name_at.get(o) == callee:
                raddr[callee] = r
        pairs = zip(calls(ours, obase, sym[s], v['n']), calls(ret, rbase, t, v['n']))

rows = ['| # | blocker | retail | ours/retail size | status | unblocks bytes | callers |',
        '|---|---|---|---|---|---|---|']
for i, (c, n) in enumerate(blocked.most_common(), 1):
    r = raddr.get(c)
    rs = inv.get(r, '?') if r else '?'
    b = bind.get(c)
    st = ('chain: ' + b['why'][0].split()[-1].split('@')[0].lstrip('?')) if b else (
        'no source' if c not in size else 'same size, bytes differ' if size[c] == rs else 'size differs')
    rows.append('| %d | `%s` | %s | %s/%s | %s | %d | %s |' % (
        i, c.split('@')[0].lstrip('?'), '%x' % r if r else '?', size.get(c, 'missing'), rs, st, n,
        ', '.join(callers[c])[:90]))
out.write_text('# Renderer blocker queue (generated by work/tools/blockers.py)\n\n'
               'Each blocker is an unverified callee; verifying it credits callers that already match.\n\n'
               + '\n'.join(rows) + '\n')
print(len(blocked), 'blockers,', sum(blocked.values()), 'game bytes blocked')
